import assert from "node:assert/strict";
import {writeFile} from "node:fs/promises";
export async function runCaseInputUI(testPage){
 const page=await testPage({viewport:{width:1440,height:1000}}),errors=[];
 page.on("pageerror",error=>errors.push(error.message));
 await page.addInitScript(()=>{
  window.isTauri=true;
  const s=window.__caseInputTest={starts:[],result:null,record:null,debugStarts:0,metadata:JSON.stringify({name:"solve",params:[{name:"nums",type:"integer[]"},{name:"target",type:"integer"}],return:{type:"integer"}})};
  const question=()=>({...window.__fixtureQuestions[0],metaData:s.metadata,sampleTestCase:"[1]\n9",exampleTestcases:"[1]\n9"});
  window.__TAURI_INTERNALS__={invoke:async(command,args={})=>{
   if(command==="load_recent_questions")return [question()];
   if(command==="get_question")return {question:question(),cacheWarning:null,fromCache:false};
   if(command==="search_questions"){const q=question();return {questions:[{frontendQuestionId:q.questionFrontendId,title:q.title,titleCn:q.translatedTitle,titleSlug:q.titleSlug,difficulty:"Easy",paidOnly:false}],total:1,hasMore:false};}
   if(command==="list_solutions")return {entries:[{id:"default",name:"默认解答"}],unreadable:0};
   if(command==="load_document")return {code:"// input fixture",notes:null};
   if(command==="external_editor_supported")return false;
   if(command==="start_language_service")throw Error("offline");
   if(command==="stop_language_service")return;
   if(command==="debug_status")return null;
   if(command==="start_debug"){s.debugStarts++;throw Error("unexpected debug admission");}
   if(command==="local_run_status")return s.result;
   if(command==="local_run_record")return s.record;
   if(command==="start_local_run"){
    const p=args.snapshot;s.starts.push(p);
    s.record={mode:p.mode,documentKey:p.documentKey,clientRequestId:p.clientRequestId,
     snapshot:{code:p.code,input:p.input,metadata:p.metadata,title:p.title,language:p.language},
     cases:p.cases,invocations:[]};
    p.cases.forEach((item,caseIndex)=>{const groups=item.input.split("\n").filter(line=>line.trim()).length/2;for(let groupIndex=0;groupIndex<groups;groupIndex++)s.record.invocations.push({caseIndex,groupIndex,caseNumber:s.record.invocations.length+1});});
    s.result={id:s.starts.length,documentKey:p.documentKey,clientRequestId:p.clientRequestId,phase:"finished",title:p.title,
     stdout:"",stderr:"",results:['{"case":1,"ok":true,"value":0}'],exitCode:0,timedOut:false,canceled:false,truncated:false,elapsedMs:1,error:""};
    return s.result.id;
   }
   throw Error("Unexpected case input IPC "+command);
  }};
 });
 await page.goto("http://127.0.0.1:5173");
 await page.getByRole("textbox",{name:"代码编辑器",exact:true}).waitFor();
 await page.getByRole("button",{name:"本地",exact:true}).click();
 const panel=page.getByRole("region",{name:"本地运行",exact:true});
 await page.getByRole("separator",{name:"调整本地面板高度",exact:true}).press("End");
 const first=panel.getByRole("textbox",{name:"参数 nums",exact:true});
 const second=panel.getByRole("textbox",{name:"参数 target",exact:true});
 await first.fill("[");await first.evaluate(node=>window.__retainedParameter=node);
 await first.press("End");await first.press("Enter");
 assert.equal(await first.inputValue(),"[\n");
 assert.equal(await first.evaluate(node=>node===window.__retainedParameter&&document.activeElement===node),true,"Enter cannot replace the focused parameter editor");
 assert.equal(await second.inputValue(),"9");
 await first.pressSequentially("  9007199254740993");
 await first.press("Enter");await first.pressSequentially("]");
 const pretty="[\n  9007199254740993\n]";
 assert.equal(await first.inputValue(),pretty,"valid JSON formatting remains editable");
 assert.equal(await first.evaluate(node=>node===window.__retainedParameter&&document.activeElement===node),true);
 await panel.getByRole("button",{name:"添加用例",exact:true}).click();
 assert.equal(await first.inputValue(),pretty,"copying a case retains its literal field draft");
 await first.fill("[");await first.press("End");await first.press("Enter");
 await panel.getByRole("tab",{name:"用例 1",exact:true}).click();
 assert.equal(await first.inputValue(),pretty);
 await panel.getByRole("tab",{name:"用例 2",exact:true}).click();
 assert.equal(await first.inputValue(),"[\n","case switching preserves incomplete field boundaries");
 await panel.getByRole("button",{name:"收起",exact:true}).click();
 await page.getByRole("button",{name:"本地",exact:true}).click();
 assert.equal(await first.inputValue(),"[\n","collapsing does not discard field drafts");
 await panel.getByRole("tab",{name:"用例 1",exact:true}).click();
 await first.fill("[");await second.fill("]\n9");
 await panel.getByRole("button",{name:"本地执行",exact:true}).click();
 await panel.getByRole("alert").filter({hasText:"需要一个完整的 JSON 值"}).waitFor();
 assert.equal(await page.evaluate(()=>window.__caseInputTest.starts.length),0,"joined valid JSON cannot disguise individually invalid fields");
 await panel.locator('[data-local-tab="debug"]').click();
 await panel.getByRole("button",{name:"开始调试",exact:true}).click();
 await panel.getByRole("alert").filter({hasText:"需要一个完整的 JSON 值"}).waitFor();
 assert.equal(await page.evaluate(()=>window.__caseInputTest.debugStarts),0,"debug uses the same structured-field admission");
 await panel.locator('[data-local-tab="run"]').click();
 await first.fill("[1]\n2\n[3]");await second.fill("4");
 await panel.getByRole("button",{name:"本地执行",exact:true}).click();
 await panel.getByRole("alert").filter({hasText:"需要一个完整的 JSON 值"}).waitFor();
 assert.equal(await page.evaluate(()=>window.__caseInputTest.starts.length),0,"structured field cannot silently create extra invocations");
 await first.fill(pretty);await second.fill("9");
 await panel.getByRole("button",{name:"运行全部用例",exact:true}).click();
 await panel.getByRole("alert").filter({hasText:"用例 2"}).waitFor();
 assert.equal(await page.evaluate(()=>window.__caseInputTest.starts.length),0,"batch admission validates hidden incomplete fields");
 await panel.getByRole("button",{name:"本地执行",exact:true}).click();
 await page.waitForFunction(()=>window.__caseInputTest.starts.length===1);
 assert.equal(await page.evaluate(()=>window.__caseInputTest.starts[0].input),"[9007199254740993]\n9","serialization preserves integer precision and parameter boundary");
 await panel.getByText("执行结束 · 1 ms",{exact:true}).waitFor();
 await panel.getByRole("button",{name:"切换为原始输入",exact:true}).click();
 const raw=panel.getByRole("textbox",{name:"本地测试输入",exact:true});
 assert.equal(await raw.inputValue(),"[9007199254740993]\n9");
 await raw.fill("[1]\n9\n[2]\n8");
 assert.equal(await raw.inputValue(),"[1]\n9\n[2]\n8","explicit raw mode preserves multi-invocation input");
 assert.equal(await panel.getByRole("button",{name:"切换为参数输入",exact:true}).isDisabled(),true);
 await panel.getByRole("button",{name:"本地执行",exact:true}).click();
 await page.waitForFunction(()=>window.__caseInputTest.starts.length===2);
 assert.equal(await page.evaluate(()=>window.__caseInputTest.starts[1].input),"[1]\n9\n[2]\n8");
 assert.equal(await page.evaluate(()=>window.__caseInputTest.record.invocations.length),2,"explicit raw mode permits two invocations");
 await panel.getByText("执行结束 · 1 ms",{exact:true}).waitFor();
 await raw.fill('[1]\n9');
 await panel.getByRole("button",{name:"切换为参数输入",exact:true}).click();
 const largeArray="["+Array.from({length:10001},(_,i)=>String(i)).join(",")+"]";
 await first.fill(largeArray);
 await panel.getByRole("button",{name:"本地执行",exact:true}).click();
 await page.waitForFunction(()=>window.__caseInputTest.starts.length===3);
 assert.equal(await page.evaluate(()=>window.__caseInputTest.starts[2].input),largeArray+"\n9","parameter validation does not impose comparison-only node limits");
 await panel.getByText("执行结束 · 1 ms",{exact:true}).waitFor();
 await panel.getByRole("button",{name:"切换为原始输入",exact:true}).click();
 await raw.fill('[1]\n9');
 await panel.getByRole("button",{name:"切换为参数输入",exact:true}).click();
 assert.equal(await second.inputValue(),"9");
 await first.fill('["a b", "c\\\\d", 9007199254740993]');
 assert.equal(await first.inputValue(),'["a b", "c\\\\d", 9007199254740993]');
 const saved=await page.evaluate(()=>JSON.parse(localStorage.getItem(Object.keys(localStorage).find(k=>k.startsWith("inkleet.test-cases.v1:")))));
 assert.equal(saved.cases[0].input,'["a b","c\\\\d",9007199254740993]\n9');
 await page.screenshot({path:"evidence/parameter-input-multiline-draft.png"});
 await panel.getByRole("tab",{name:"用例 2",exact:true}).click();
 await page.evaluate(()=>{window.__caseInputTest.metadata=JSON.stringify({params:[{name:"only",type:"integer"}]});});
 await page.locator('.question-sidebar [data-slug="inkleet-test-fixture"]').click();
 await page.waitForFunction(()=>document.querySelector('.local-runner [aria-label="本地测试输入"]')?.value==="[\n\n9");
 assert.equal(await panel.getByRole("textbox",{name:"参数 undefined",exact:true}).count(),0,"schema refresh cannot retain old labeled fields");
 assert.equal(await panel.getByRole("button",{name:"切换为原始输入",exact:true}).count(),0);
 await page.evaluate(()=>{window.__caseInputTest.metadata=JSON.stringify({systemdesign:true,params:[]});});
 await page.locator('.question-sidebar [data-slug="inkleet-test-fixture"]').click();
 await panel.getByRole("textbox",{name:"本地测试输入",exact:true}).waitFor();
 assert.equal(await panel.getByRole("textbox",{name:"本地测试输入",exact:true}).inputValue(),"[\n\n9");
 await page.reload();
 await page.getByRole("textbox",{name:"代码编辑器",exact:true}).waitFor();
 await page.getByRole("button",{name:"本地",exact:true}).click();
 const restored=page.getByRole("region",{name:"本地运行",exact:true}).getByRole("textbox",{name:"本地测试输入",exact:true});
 assert.equal(await restored.inputValue(),"[\n\n9","reload preserves malformed text without inventing lost parameter boundaries");
 assert.deepEqual(errors,[]);
 await page.close();
 await writeFile("evidence/CASE_INPUT_DRAFT_RESULT.txt","PASS: real multiline parameter typing preserves focused DOM node and literal drafts; case copy/switch/collapse retain incomplete boundaries; serialization keeps exact large integers/strings; explicit raw mode retains multi-group input; malformed persisted text reloads losslessly as raw. Mocked local-run IPC, not compiler acceptance.\n");
}
